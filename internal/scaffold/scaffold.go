// GxModule is the import path of the framework.
const GxModule = "github.com/alternayte/gx"

// Options configure `gx init`.
type Options struct {
	// Dir is the directory of the new app. It may exist when it holds no
	// app.
	Dir string
	// Module is the Go module path. It defaults to the directory name.
	Module string
	// Adapter is the hypermedia adapter: "datastar" or "htmx".
	Adapter string
	// Version is the Gx release the app requires, without the "v".
	Version string
	// Replace points the Gx module at a local checkout, for work on Gx
	// itself.
	Replace string
	// Registry is the component registry URL or directory in gx.toml. It
	// defaults to the official registry of Version.
	Registry string
	// Template is "app" (the default) or "docs": a docs site with the
	// docs shell and the docs kit of the registry (REQ-CNT-06).
	Template string
}

// data is what every template reads.
type data struct {
	// Name is the app name: the directory name.
	Name string
	// Title is the name with an upper-case first letter.
	Title string
	// Adapter is the adapter name: "datastar" or "htmx". Htmx is true for
	// the adapter with no signals, so the example slice keeps its state
	// on the server.
	Adapter string
	Htmx    bool
	Module  string
	Version string
	Replace string
	// Registry is the registry source in gx.toml.
	Registry string
	// Slice, Type and the rest describe the code of one `gx new` call.
	Slice string
	Type  string
	Kebab string
	Label string
	Pkg   string
}

// CheckAdapter reports whether Gx has the adapter (REQ-ACT-09).
func CheckAdapter(adapter string) error {
	switch adapterName(adapter) {
	case gxconfig.AdapterDatastar, gxconfig.AdapterHtmx:
		return nil
	default:
		return fmt.Errorf("unknown adapter %q; the adapters are datastar and htmx", adapter)
	}
}

// adapterName returns the adapter name as gx.toml and the adapter package
// write it.
func adapterName(adapter string) string {
	return strings.ToLower(strings.TrimSpace(adapter))
}

var packageName = regexp.MustCompile(`^[a-z][a-z0-9]*$`)

// OfficialRegistry returns the URL of the official registry of a release.
func OfficialRegistry(version string) string {
	return "https://raw.githubusercontent.com/alternayte/gx/v" + version + "/registry"
}

// Init writes a new app and returns the files it wrote, relative to the app
// directory (REQ-DEV-10). It refuses a directory that already holds an app.
func Init(opt Options) ([]string, error) {
	if err := CheckAdapter(opt.Adapter); err != nil {
		return nil, err
	}
	if opt.Template == "" {
		opt.Template = "app"
	}
	if opt.Template != "app" && opt.Template != "docs" {
		return nil, fmt.Errorf("unknown template %q; gx init has app and docs", opt.Template)
	}
	dir, err := filepath.Abs(opt.Dir)
	if err != nil {
		return nil, err
	}
	for _, name := range []string{"go.mod", "gx.toml"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			return nil, fmt.Errorf("%s already holds %s; gx init makes a new app and changes no existing one", dir, name)
		}
	}
	name := appName(filepath.Base(dir))
	d := data{
		Name:     name,
		Title:    upperFirst(name),
		Adapter:  adapterName(opt.Adapter),
		Htmx:     adapterName(opt.Adapter) == gxconfig.AdapterHtmx,
		Module:   opt.Module,
		Version:  opt.Version,
		Registry: opt.Registry,
	}
	if d.Module == "" {
		d.Module = name
	}
	if d.Registry == "" {
		d.Registry = OfficialRegistry(opt.Version)
	}
	if opt.Replace != "" {
		abs, err := filepath.Abs(opt.Replace)
		if err != nil {
			return nil, err
		}
		d.Replace = filepath.ToSlash(abs)
	}
	files := map[string]string{
		"app/theme.css":         gx.DefaultThemeCSS,
		"gxstyles/styles_gx.go": string(gxstyles.Generate(nil)),
		"gxstyles/tokens_gx.go": string(gxstyles.GenerateTokens([]byte(gx.DefaultThemeCSS))),
		// The first island needs no edit of main: the bundle is installed
		// from the start, and gx build fills it.
		"gxislands/islands_gx.go": string(islands.Generate(nil)),
		"AGENTS.md":               Agents(d.Name, d.Adapter),
		// go mod tidy reads every build tag, so the gallery package of
		// the dev build must exist before the first generate fills it.
		"gxdev_gallery/gallery_gx.go": "// Code generated by gx. DO NOT EDIT.\n\n//go:build gxdev\n\npackage gxdev_gallery\n\nimport gx \"" + GxModule + "\"\n\n// Fixtures returns every component fixture for the dev gallery.\nfunc Fixtures() []gx.Fixture { return nil }\n",
		// The same holds for the dev symbol table (REQ-DEV-04).
		"gxdev_symbols/symbols_gx.go": "// Code generated by gx. DO NOT EDIT.\n\n//go:build gxdev\n\npackage gxdev_symbols\n\nimport gx \"" + GxModule + "\"\n\n// Packages returns the symbol table.\nfunc Packages() []gx.DevPackage { return nil }\n",
	}
	templates := map[string]string{}
	for rel, text := range initFiles {
		templates[rel] = text
	}
	own := appFiles
	if opt.Template == "docs" {
		own, err = docsFiles()
		if err != nil {
			return nil, err
		}
	}
	for rel, text := range own {
		templates[rel] = text
	}
	for rel, text := range templates {
		body, err := render(rel, text, d)
		if err != nil {
			return nil, err
		}
		files[rel] = body
	}
	written, err := writeNew(dir, files)
	if err != nil {
		return nil, err
	}
	if opt.Template == "docs" {
		// The docs site owns its shell and its components: gx add copies
		// them from the registry, as it does for every later item.
		installer := registry.Installer{Root: dir, Source: d.Registry, Dir: "ui"}
		for _, item := range []string{"docs-shell", "docs"} {
			added, err := installer.Add(item, "")
			if err != nil {
				return written, fmt.Errorf("gx add %s: %w\nThe files are written. Set [registry] url in gx.toml, then run `go run ./cmd/gx add %s`", item, err, item)
			}
			for _, a := range added {
				for _, f := range a.Files {
					written = append(written, f.Target)
				}
			}
		}
	}
	if err := tidy(dir); err != nil {
		return written, err
	}
	generated, err := Generate(dir)
	if err != nil {
		return written, err
	}
	written = append(written, generated...)
	sort.Strings(written)
	return written, nil
}

// appName makes a directory name a lower-case name with no spaces.
func appName(base string) string {
	name := strings.ToLower(strings.TrimSpace(base))
	name = regexp.MustCompile(`[^a-z0-9._-]+`).ReplaceAllString(name, "-")
	if name == "" || name == "." {
		return "app"
	}
	return name
}

// render runs one template.
func render(name, text string, d data) (string, error) {
	t, err := template.New(name).Delims("«", "»").Parse(text)
	if err != nil {
		return "", err
	}
	var b bytes.Buffer
	if err := t.Execute(&b, d); err != nil {
		return "", err
	}
	return b.String(), nil
}

// writeNew writes files under dir. It checks every target first, so it
// writes all the files or none.
func writeNew(dir string, files map[string]string) ([]string, error) {
	rels := make([]string, 0, len(files))
	for rel := range files {
		rels = append(rels, rel)
	}
	sort.Strings(rels)
	for _, rel := range rels {
		if _, err := os.Stat(filepath.Join(dir, filepath.FromSlash(rel))); err == nil {
			return nil, fmt.Errorf("%s exists; nothing is written", rel)
		}
	}
	for _, rel := range rels {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, []byte(files[rel]), 0o644); err != nil {
			return nil, err
		}
	}
	return rels, nil
}

// tidy resolves the module graph of the new app.
func tidy(dir string) error {
	cmd := exec.Command("go", "mod", "tidy")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("go mod tidy: %w\n%sThe files are written. Run `go mod tidy`, then `go run ./cmd/gx generate`", err, out)
	}
	return nil
}

// Generate writes the generated Go of the app and returns the files,
// relative to dir.
func Generate(dir string) ([]string, error) {
	files, diags := compiler.Generate(dir)
	if len(diags) > 0 {
		lines := make([]string, 0, len(diags))
		for _, d := range diags {
			lines = append(lines, d.String())
		}
		return nil, fmt.Errorf("the new code does not check:\n%s", strings.Join(lines, "\n"))
	}
	var out []string
	for path, src := range files {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, src) {
			continue
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			return nil, err
		}
		if rel, err := filepath.Rel(dir, path); err == nil {
			out = append(out, filepath.ToSlash(rel))
		}
	}
	sort.Strings(out)
	return out, nil
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

