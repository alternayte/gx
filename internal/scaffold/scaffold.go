//go:embed templates/docs/*.tmpl
var docsTemplates embed.FS

// docsFiles returns the templates only the docs template writes
// (REQ-CNT-06): the docs slice, the app main and three pages.
func docsFiles() (map[string]string, error) {
	out := map[string]string{}
	for target, name := range map[string]string{
		"site/site.go":                        "site.go.tmpl",
		"cmd/app/main.go":                     "main.go.tmpl",
		"content/docs/index.md":               "index.md.tmpl",
		"content/docs/start.md":               "start.md.tmpl",
		"content/docs/guides/write-a-page.md": "write-a-page.md.tmpl",
	} {
		data, err := docsTemplates.ReadFile("templates/docs/" + name)
		if err != nil {
			return nil, err
		}
		out[target] = string(data)
	}
	return out, nil
}
