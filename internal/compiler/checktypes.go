package compiler

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"

	"golang.org/x/tools/go/packages"
)

// checkTypes type-checks the Go expressions of every .gx file in dirs. It
// generates shadow Go files in memory and never writes them to disk.
func (l *loader) checkTypes(root string, dirs []string) []Diagnostic {
	if findModule(root) == nil {
		return nil
	}
	names := map[string]string{} // synthetic probe name -> .gx path
	overlay := map[string][]byte{}
	i := 0
	for _, dir := range dirs {
		p := l.load(dir)
		for base, f := range p.Files {
			if f.Package == "" {
				continue
			}
			synth := fmt.Sprintf("gx%d", i)
			i++
			names[synth] = f.File
			overlay[filepath.Join(dir, base+"_gx.go")] = buildProbe(f, synth)
		}
	}
	if len(overlay) == 0 {
		return nil
	}
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps,
		Dir:     root,
		Overlay: overlay,
	}
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return nil
	}
	var out []Diagnostic
	for _, pkg := range pkgs {
		for _, e := range pkg.TypeErrors {
			pos := pkg.Fset.Position(e.Pos)
			file, ok := names[filepath.Base(pos.Filename)]
			if !ok {
				continue
			}
			out = append(out, Diagnostic{
				Code: CodeType,
				File: file,
				Line: pos.Line,
				Col:  pos.Column,
				Msg:  e.Msg,
			})
		}
	}
	return out
}

// buildProbe returns a shadow Go file for f. The file declares the props
// type and the component function so that callers type-check, and probes
// every server expression. It is never written to disk.
func buildProbe(f *File, synth string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by gx for type checking. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", f.Package)
	b.WriteString("import (\n")
	b.WriteString("\tgx \"github.com/alternayte/gx\"\n")
	for _, im := range f.Imports {
		if importPath(im.Raw) == "github.com/alternayte/gx" {
			continue
		}
		fmt.Fprintf(&b, "\t%s\n", im.Raw)
	}
	b.WriteString(")\n\n")
	name := componentName(f)
	fmt.Fprintf(&b, "type %sProps struct {\n", name)
	for _, fld := range f.Props {
		lineDirective(&b, synth, fld.At)
		fmt.Fprintf(&b, "%s %s\n", fld.Name, fld.Type)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func %s(p %sProps) gx.Node { return nil }\n\n", name, name)
	fmt.Fprintf(&b, "func _gxProbe%s(p %sProps) {\n", name, name)
	writeProbe(&b, f.Body, synth)
	b.WriteString("}\n")
	return b.Bytes()
}

func writeProbe(b *bytes.Buffer, ns []Node, synth string) {
	for _, n := range ns {
		switch t := n.(type) {
		case *Expr:
			writeProbeExpr(b, t.Data, t.DataAt, synth)
		case *Element:
			for i := range t.Attrs {
				a := &t.Attrs[i]
				if a.Kind == AttrExpr {
					writeProbeExpr(b, a.Value, a.ValueAt, synth)
				}
			}
			if !t.HasRaw {
				writeProbe(b, t.Children, synth)
			}
		case *Let:
			if strings.Contains(t.Expr, "$") {
				continue
			}
			lineDirective(b, synth, t.At)
			fmt.Fprintf(b, "%s := %s\n", t.Name, t.Expr)
		case *Control:
			writeProbeControl(b, t, synth)
		}
	}
}

func writeProbeControl(b *bytes.Buffer, c *Control, synth string) {
	lineDirective(b, synth, c.At)
	switch c.Kind {
	case "if":
		fmt.Fprintf(b, "if %s {\n", c.Header)
		writeProbe(b, c.Body, synth)
		b.WriteString("}")
		if len(c.Else) > 0 {
			b.WriteString(" else {\n")
			writeProbe(b, c.Else, synth)
			b.WriteString("}")
		}
		b.WriteString("\n")
	case "for":
		fmt.Fprintf(b, "for %s {\n", c.Header)
		writeProbe(b, c.Body, synth)
		b.WriteString("}\n")
	case "switch":
		fmt.Fprintf(b, "switch %s {\n", c.Header)
		for _, cs := range c.Cases {
			if cs.IsDefault {
				b.WriteString("default:\n")
			} else {
				fmt.Fprintf(b, "case %s:\n", cs.Header)
			}
			writeProbe(b, cs.Body, synth)
		}
		b.WriteString("}\n")
	}
}

func writeProbeExpr(b *bytes.Buffer, expr string, at Pos, synth string) {
	expr = strings.TrimSpace(expr)
	if expr == "" || strings.Contains(expr, "$") || at.Line <= 0 {
		return
	}
	// The prefix "_=" is two columns wide, so the expression starts at
	// the column the directive names.
	col := at.Col - 2
	if col < 1 {
		col = 1
	}
	fmt.Fprintf(b, "//line %s:%d:%d\n_=%s\n", synth, at.Line, col, expr)
}

func lineDirective(b *bytes.Buffer, synth string, at Pos) {
	if at.Line <= 0 {
		return
	}
	col := at.Col
	if col <= 0 {
		col = 1
	}
	fmt.Fprintf(b, "//line %s:%d:%d\n", synth, at.Line, col)
}

// componentName returns the component name of f: the file base name.
func componentName(f *File) string {
	base := filepath.Base(f.File)
	return strings.TrimSuffix(base, ".gx")
}

func importPath(raw string) string {
	_, path, _ := splitImport(raw)
	return path
}
