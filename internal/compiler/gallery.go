// galleryPackage is the generated package the app's gxdev main imports to
// install the dev gallery (REQ-AI-03).
const galleryPackage = "gxdev_gallery"

// galleryFilePath is the output path of the generated gallery registry.
func galleryFilePath(root string) string {
	return filepath.Join(root, galleryPackage, "gallery_gx.go")
}

// fixtureSet is one <Name>.fixtures.go declaration.
type fixtureSet struct {
	component string   // component name, from the file base
	varName   string   // the declared gx.Fixtures var
	wrapVar   string   // optional <Component>Wrap(n) gx.Node function
	keys      []string // fixture names, sorted
	file      string   // the component's .gx file
}

// componentEntry is one component of the module for the gallery.
type componentEntry struct {
	name    string
	pkgName string
	pkgPath string
	dir     string
}

// renderGallery renders the gxdev gallery registry: one entry per fixture
// and a Missing entry per component without one (REQ-AI-03).
func renderGallery(root string, dirs []string, l *loader, pkgs []*packages.Package) []byte {
	fixtures := collectFixtures(pkgs)
	var comps []componentEntry
	seen := map[string]bool{}
	for _, dir := range dirs {
		p := l.load(dir)
		if p.Module == nil {
			continue
		}
		pkgPath := modulePathOf(p.Module, dir)
		pkgName := ""
		for _, file := range p.Files {
			name := componentName(file)
			if name == "" || seen[dir+"/"+name] {
				continue
			}
			seen[dir+"/"+name] = true
			if pkgName == "" {
				pkgName = file.Package
			}
			comps = append(comps, componentEntry{name: name, pkgName: pkgName, pkgPath: pkgPath, dir: dir})
		}
	}
	sort.Slice(comps, func(i, j int) bool {
		if comps[i].pkgPath != comps[j].pkgPath {
			return comps[i].pkgPath < comps[j].pkgPath
		}
		return comps[i].name < comps[j].name
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by gx. DO NOT EDIT.\n\n")
	b.WriteString("//go:build gxdev\n\n")
	fmt.Fprintf(&b, "package %s\n\n", galleryPackage)
	b.WriteString("import (\n")
	b.WriteString("\tgx \"github.com/alternayte/gx\"\n")
	aliases := map[string]string{}
	aliasUsed := map[string]bool{}
	imported := map[string]bool{}
	for i, comp := range comps {
		set, ok := fixtures[filepath.Clean(filepath.Join(comp.dir, comp.name+".gx"))]
		if !ok || len(set.keys) == 0 {
			continue // a missing entry needs no import
		}
		if imported[comp.pkgPath] {
			continue
		}
		imported[comp.pkgPath] = true
		alias := comp.pkgName
		if alias == "" {
			alias = fmt.Sprintf("pkg%d", i)
		}
		if aliasUsed[alias] {
			alias = fmt.Sprintf("%s%d", alias, i)
		}
		aliasUsed[alias] = true
		aliases[comp.pkgPath] = alias
		fmt.Fprintf(&b, "\t%s \"%s\"\n", alias, comp.pkgPath)
	}
	b.WriteString(")\n\n")
	b.WriteString("// Fixtures returns every component fixture for the dev gallery\n// (REQ-AI-03).\nfunc Fixtures() []gx.Fixture {\n\treturn []gx.Fixture{\n")
	for _, comp := range comps {
		set, ok := fixtures[filepath.Clean(filepath.Join(comp.dir, comp.name+".gx"))]
		if !ok || len(set.keys) == 0 {
			fmt.Fprintf(&b, "\t\t{Component: %q, Package: %q, Missing: true},\n", comp.name, comp.pkgPath)
			continue
		}
		alias := aliases[comp.pkgPath]
		for _, key := range set.keys {
			if set.wrapVar != "" {
				fmt.Fprintf(&b, "\t\t{Component: %q, Package: %q, Name: %q, Node: func() gx.Node { return %s.%s(%s.%s(%s.%s[%q])) }},\n",
					comp.name, comp.pkgPath, key, alias, set.wrapVar, alias, comp.name, alias, set.varName, key)
				continue
			}
			fmt.Fprintf(&b, "\t\t{Component: %q, Package: %q, Name: %q, Node: func() gx.Node { return %s.%s(%s.%s[%q]) }},\n",
				comp.name, comp.pkgPath, key, alias, comp.name, alias, set.varName, key)
		}
	}
	b.WriteString("\t}\n}\n")
	return b.Bytes()
}

// modulePathOf returns the import path of a package directory.
func modulePathOf(mod *Module, dir string) string {
	rel, err := filepath.Rel(mod.Dir, dir)
	if err != nil || rel == "." {
		return mod.Path
	}
	return mod.Path + "/" + filepath.ToSlash(rel)
}

// collectFixtures finds every gx.Fixtures[T] declaration, keyed by the
// component's .gx file.
func collectFixtures(pkgs []*packages.Package) map[string]fixtureSet {
	out := map[string]fixtureSet{}
	for _, pkg := range pkgs {
		for _, file := range pkg.Syntax {
			path := pkg.Fset.Position(file.Pos()).Filename
			base := filepath.Base(path)
			if !strings.HasSuffix(base, ".fixtures.go") {
				continue
			}
			component := strings.TrimSuffix(base, ".fixtures.go")
			gxFile := filepath.Join(filepath.Dir(path), component+".gx")
			for _, decl := range file.Decls {
				if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil && fn.Name.Name == component+"Wrap" {
					set := out[filepath.Clean(gxFile)]
					set.component, set.file, set.wrapVar = component, gxFile, fn.Name.Name
					out[filepath.Clean(gxFile)] = set
					continue
				}
				gen, ok := decl.(*ast.GenDecl)
				if !ok || gen.Tok != token.VAR {
					continue
				}
				for _, spec := range gen.Specs {
					vs, ok := spec.(*ast.ValueSpec)
					if !ok || len(vs.Names) == 0 {
						continue
					}
					set := fixtureSet{component: component, varName: vs.Names[0].Name, file: gxFile}
					if prev, ok := out[filepath.Clean(gxFile)]; ok {
						set.wrapVar = prev.wrapVar
					}
					if vs.Type != nil && isGxFixturesType(pkg, vs.Type) {
						// A declared type without a literal has no keys yet.
					}
					for _, value := range vs.Values {
						lit, ok := value.(*ast.CompositeLit)
						if !ok {
							continue
						}
						if lit.Type != nil && !isGxFixturesType(pkg, lit.Type) {
							continue
						}
						if lit.Type == nil && !isGxFixturesType(pkg, vs.Type) {
							continue
						}
						for _, elt := range lit.Elts {
							kv, ok := elt.(*ast.KeyValueExpr)
							if !ok {
								continue
							}
							switch key := kv.Key.(type) {
							case *ast.BasicLit:
								if s, err := strconv.Unquote(key.Value); err == nil {
									set.keys = append(set.keys, s)
								}
							case *ast.Ident:
								set.keys = append(set.keys, key.Name)
							}
						}
					}
					sort.Strings(set.keys)
					out[filepath.Clean(gxFile)] = set
				}
			}
		}
	}
	return out
}

// isGxFixturesType reports whether a type expression is gx.Fixtures[...].
func isGxFixturesType(pkg *packages.Package, expr ast.Expr) bool {
	if expr == nil {
		return false
	}
	var sel *ast.SelectorExpr
	switch t := expr.(type) {
	case *ast.IndexExpr:
		sel, _ = t.X.(*ast.SelectorExpr)
	case *ast.IndexListExpr:
		sel, _ = t.X.(*ast.SelectorExpr)
	case *ast.SelectorExpr:
		sel = t
	default:
		return false
	}
	if sel == nil {
		return false
	}
	obj := pkg.TypesInfo.Uses[sel.Sel]
	return obj != nil && obj.Pkg() != nil && obj.Pkg().Path() == "github.com/alternayte/gx" && obj.Name() == "Fixtures"
}
