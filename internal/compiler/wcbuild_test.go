package compiler_test

import (
	"strings"
	"testing"

	"github.com/alternayte/gx/internal/compiler"
)

const wcEvents = "package cart\n\nimport \"github.com/alternayte/gx\"\n\n" +
	"type Mode string\n\nconst (\n\tQuick Mode = \"quick\"\n\tFull  Mode = \"full\"\n)\n\n" +
	"type Line struct {\n\tSKU string `json:\"sku\"`\n\tQty int    `json:\"qty\"`\n}\n\n" +
	"type ChangedDetail struct {\n\tCount int    `json:\"count\"`\n\tLines []Line `json:\"lines\"`\n\tMode  Mode   `json:\"mode\"`\n\tNote  *string `json:\"note,omitempty\"`\n}\n\n" +
	"var Changed = gx.Event[ChangedDetail](\"cart-changed\")\n\nvar Cleared = gx.Event[struct{}](\"cart-cleared\")\n"

const wcRoutes = "package route\n\nimport \"github.com/alternayte/gx\"\n\n" +
	"type Widget struct {\n\tgx.Route `GET /cart`\n\tCurrency string `query:\"currency\" default:\"EUR\"`\n\tCompact  bool   `query:\"compact\"`\n\tLimit    int    `query:\"limit\" default:\"10\"`\n\tView     string `query:\"view\"`\n\tTaxRate  float64 `query:\"tax-rate\"`\n}\n\n" +
	"type Add struct {\n\tgx.Route `POST /cart/add`\n}\n"

const wantDTS = `// Code generated by gx wc build. DO NOT EDIT.

export type Mode = "full" | "quick";

export interface ChangedDetail {
  count: number;
  lines: Line[];
  mode: Mode;
  note?: string;
}

export interface Line {
  sku: string;
  qty: number;
}

/** The attributes of <acme-cart>. The element sends each one to the Gx server. */
export interface AcmeCartAttributes {
  /** Default "EUR". */
  currency?: string;
  compact?: boolean;
  /** Default "10". */
  limit?: number;
  view?: string;
  "tax-rate"?: number;
}

/** The detail of gx-error: a status and a message key. */
export interface GxWidgetError {
  status: number;
  key: string;
  field?: string;
}

/** The token of the host for the widget: text, or a function that gives the text now. */
export type GxWidgetToken = string | (() => string | Promise<string>) | undefined;

/** The events of <acme-cart>. */
export interface AcmeCartEventMap extends HTMLElementEventMap {
  "cart-changed": CustomEvent<ChangedDetail>;
  "cart-cleared": CustomEvent<{}>;
  "gx-ready": CustomEvent<null>;
  "gx-error": CustomEvent<GxWidgetError>;
  "gx-navigate": CustomEvent<{ url: string }>;
}

export declare class AcmeCartElement extends HTMLElement {
  /** Sent as a bearer header on each request of the widget. It is never an attribute. */
  token: GxWidgetToken;
  addEventListener<K extends keyof AcmeCartEventMap>(type: K, listener: (this: AcmeCartElement, ev: AcmeCartEventMap[K]) => unknown, options?: boolean | AddEventListenerOptions): void;
  addEventListener(type: string, listener: EventListenerOrEventListenerObject, options?: boolean | AddEventListenerOptions): void;
  removeEventListener<K extends keyof AcmeCartEventMap>(type: K, listener: (this: AcmeCartElement, ev: AcmeCartEventMap[K]) => unknown, options?: boolean | EventListenerOptions): void;
  removeEventListener(type: string, listener: EventListenerOrEventListenerObject, options?: boolean | EventListenerOptions): void;
}

declare global {
  interface HTMLElementTagNameMap {
    "acme-cart": AcmeCartElement;
  }
}
`

// TestREQ_ISL_10_WidgetContract checks what gx wc build knows about a
// widget: its path with the prefix of the group, its attributes from the
// route input, and its type file (REQ-ISL-10). The type file has the detail
// type of each domain event of the package, from the Go struct
// (REQ-ISL-17).
func TestREQ_ISL_10_WidgetContract(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod":              moduleWithGx(t),
		"cart/route/route.go": wcRoutes,
		"cart/Cart.gx":        widgetGx,
		"cart/cart.go":        widgetGo(`.Tag("acme-cart")`),
		"cart/events.go":      wcEvents,
		"main.go":             widgetMain("\tapp.Group(\"/widgets\", gx.AllowOrigins(\"https://shop.example.com\"), cart.Routes)\n"),
	})
	widgets, diags := compiler.Widgets(dir)
	if len(diags) != 0 {
		t.Fatalf("diagnostics: %v", diags)
	}
	if len(widgets) != 1 {
		t.Fatalf("widgets = %d, want 1", len(widgets))
	}
	w := widgets[0]
	if w.Tag != "acme-cart" || w.Class != "AcmeCart" || w.Path != "/widgets/cart" {
		t.Errorf("tag %q, class %q, path %q", w.Tag, w.Class, w.Path)
	}
	var names []string
	for _, a := range w.Attributes {
		names = append(names, a.Name+":"+a.Type+":"+a.Default)
	}
	if got, want := strings.Join(names, " "), `currency:string:EUR compact:boolean: limit:number:10 view:string: tax-rate:number:`; got != want {
		t.Errorf("attributes = %s\nwant         %s", got, want)
	}
	if got := string(w.DTS); got != wantDTS {
		t.Errorf("type file:\n%s\nwant:\n%s", got, wantDTS)
	}
	react := string(w.ReactDTS)
	for _, want := range []string{
		`import type { AcmeCartAttributes, AcmeCartElement, AcmeCartEventMap } from "./acme-cart";`,
		"[K in \"cart-changed\" | \"cart-cleared\" | \"gx-ready\" | \"gx-error\" | \"gx-navigate\" as `on${K}`]?: (event: AcmeCartEventMap[K]) => void;",
		`"acme-cart": DetailedHTMLProps<HTMLAttributes<AcmeCartElement>, AcmeCartElement> & AcmeCartAttributes & AcmeCartEvents;`,
	} {
		if !strings.Contains(react, want) {
			t.Errorf("the React type file has no %s\n%s", want, react)
		}
	}
	manifest, err := compiler.WidgetManifest(widgets)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`"schemaVersion": "1.0.0"`, `"tagName": "acme-cart"`, `"name": "currency"`, `"default": "EUR"`, `"name": "cart-changed"`, `"text": "CustomEvent<ChangedDetail>"`, `"name": "token"`, `"kind": "custom-element-definition"`} {
		if !strings.Contains(string(manifest), want) {
			t.Errorf("the manifest has no %s\n%s", want, manifest)
		}
	}
}

// TestREQ_ISL_17_EventDetailNeedsATypeScriptType checks that gx wc build
// stops for a detail type with no TypeScript form.
func TestREQ_ISL_17_EventDetailNeedsATypeScriptType(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"go.mod":              moduleWithGx(t),
		"cart/route/route.go": wcRoutes,
		"cart/Cart.gx":        widgetGx,
		"cart/cart.go":        widgetGo(`.Tag("acme-cart")`),
		"cart/events.go":      "package cart\n\nimport \"github.com/alternayte/gx\"\n\ntype Detail struct {\n\tDone chan int\n}\n\nvar Changed = gx.Event[Detail](\"cart-changed\")\n",
		"main.go":             widgetMain("\tapp.Group(\"/widgets\", gx.AllowOrigins(gx.AnyOrigin), cart.Routes)\n"),
	})
	widgets, diags := compiler.Widgets(dir)
	if len(widgets) != 0 || len(diags) != 1 || !strings.Contains(diags[0].Msg, "cart-changed") || !strings.Contains(diags[0].Msg, "Done") {
		t.Fatalf("widgets %d, diagnostics %v; want one diagnostic for the detail field Done", len(widgets), diags)
	}
}
