// The generated Go encoder writes the JSON that the generated TypeScript
// type describes. With no nil slice, map or pointer in the value, that is
// the JSON of encoding/json byte for byte.
func TestREQ_ISL_02_EncoderMatchesTheType(t *testing.T) {
	dir := mappingTree(t, map[string]string{
		"dash/Page.gx": "package dash\n\nprops {\n  Title string\n}\n\n<section><RevenueChart title={p.Title} stacked /></section>\n",
		"main.go": `package main

import (
	"encoding/json"
	"fmt"
	"html"
	"strings"
	"time"

	"app/dash"
	gx "github.com/alternayte/gx"
)

func props(n gx.Node) string {
	out := gx.String(n)
	_, rest, _ := strings.Cut(out, ` + "` props=\"`" + `)
	value, _, _ := strings.Cut(rest, ` + "`\"`" + `)
	return html.UnescapeString(value)
}

func main() {
	label := "a \"label\" <b> & \u2028 é"
	at := time.Date(2026, 10, 6, 12, 30, 0, 500, time.FixedZone("x", 3600))
	p := dash.RevenueChartProps{
		Data: []dash.Point{
			{X: 1.5, Y: -2, At: at, Label: &label, Tags: []string{"a", "b"}},
			{X: 1e21, Y: 9007199254740991, At: at.UTC(), Label: &label, Tags: []string{"\x01\t\n"}},
			{X: 1e-7, Label: &label, Tags: []string{"x"}},
		},
		Title:   "Revenue",
		Kind:    dash.Bar,
		Stacked: true,
		Count:   255,
		Totals:  map[string]float64{"b": 2, "a": 1, "c": 0.1},
		Axis:    &dash.Axis{Min: -1, Max: 10},
		Tree:    dash.Tree{Name: "root", Children: []dash.Tree{{Name: "leaf", Children: []dash.Tree{}}}},
		Since:   at,
		Note:    "note",
		Ignored: "never",
		Pairs:   [2]int{3, 4},
		Maybe:   []*dash.Point{{Label: &label, Tags: []string{"y"}}},
		NoTag:   7,
		Dash:    8,
	}
	p.Inline.A = 5
	want, err := json.Marshal(p)
	if err != nil {
		panic(err)
	}
	got := props(dash.RevenueChart(p))
	if got != string(want) {
		fmt.Printf("DIFFERENT\n got %s\nwant %s\n", got, want)
		return
	}
	fmt.Println("EQUAL")
	fmt.Println(props(dash.RevenueChart(dash.RevenueChartProps{Maybe: []*dash.Point{nil}})))
	fmt.Println(gx.String(dash.Page(dash.PageProps{Title: "Q1"})))
}
`,
	})
	writeGenerated(t, dir)
	cmd := exec.Command("go", "run", ".")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run: %v\n%s", err, out)
	}
	lines := strings.Split(strings.TrimSpace(string(out)), "\n")
	if len(lines) != 3 || lines[0] != "EQUAL" {
		t.Fatalf("output:\n%s", out)
	}
	// A nil slice is [], a nil map is {}, a nil pointer in a field is an
	// absent key and a nil pointer in a list is null.
	zero := `{"data":[],"title":"","kind":"","stacked":false,"count":0,"totals":{},"tree":{"name":"","children":[]},"pairs":[0,0],"inline":{"a":0},"maybe":[null],"NoTag":0,"dash-name":0}`
	if lines[1] != zero {
		t.Fatalf("zero props =\n%s\nwant\n%s", lines[1], zero)
	}
	page := `<section><gx-island name="app/dash/RevenueChart" props="{&#34;data&#34;:[],&#34;title&#34;:&#34;Q1&#34;,&#34;kind&#34;:&#34;&#34;,&#34;stacked&#34;:true,`
	if !strings.HasPrefix(lines[2], page) {
		t.Fatalf("page = %s\nwant prefix %s", lines[2], page)
	}
}

func TestREQ_ISL_02_GeneratedGoIsFormatted(t *testing.T) {
	dir := mappingTree(t, nil)
	files := generateFiles(t, dir)
	path := filepath.Join(dir, "dash", "RevenueChart_gx.go")
	src, ok := files[path]
	if !ok {
		t.Fatal("no RevenueChart_gx.go in the generated files")
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("gofmt", "-l", path).CombinedOutput()
	if err != nil || len(out) != 0 {
		t.Fatalf("gofmt -l: %v %s\n%s", err, out, src)
	}
	if strings.Contains(string(src), "reflect") || strings.Contains(string(src), "encoding/json") {
		t.Fatalf("the encoder uses reflection:\n%s", src)
	}
}

func TestREQ_ISL_02_UnsupportedType(t *testing.T) {
	cases := map[string]struct {
		field string
		decl  string
		want  string
	}{
		"interface":    {field: "V any `json:\"v\"`", want: "an interface has no mapping"},
		"func":         {field: "V func() `json:\"v\"`", want: "this type has no mapping"},
		"chan":         {field: "V chan int `json:\"v\"`", want: "this type has no mapping"},
		"complex":      {field: "V complex128 `json:\"v\"`", want: "this type has no mapping"},
		"int key":      {field: "V map[int]string `json:\"v\"`", want: "a map needs string keys"},
		"bytes":        {field: "V []byte `json:\"v\"`", want: "a byte slice has no mapping"},
		"embedded":     {field: "Base", decl: "type Base struct{ A int }", want: "an embedded field has no mapping"},
		"marshaler":    {field: "V Money `json:\"v\"`", decl: "type Money struct{ Cents int }\n\nfunc (m Money) MarshalJSON() ([]byte, error) { return nil, nil }", want: "a MarshalJSON method"},
		"string opt":   {field: "V int `json:\"v,string\"`", want: `the json option "string"`},
		"same name":    {field: "V int `json:\"title\"`", want: `a second field has the JSON name "title"`},
		"ptr ptr":      {field: "V **int `json:\"v\"`", want: "a pointer to a pointer"},
		"nested":       {field: "V []Inner `json:\"v\"`", decl: "type Inner struct{ F func() }", want: `"V[].F"`},
		"omitzero":     {field: "V Inner `json:\"v,omitzero\"`", decl: "type Inner struct{ S []int }", want: "omitzero needs a type"},
		"own cycle":    {field: "V struct{ Next *RevenueChartProps; C chan int } `json:\"v\"`", want: `"V.C"`},
		"uintptr":      {field: "V uintptr `json:\"v\"`", want: "a uintptr has no mapping"},
		"text marshal": {field: "V Level `json:\"v\"`", decl: "type Level int\n\nfunc (l Level) MarshalText() ([]byte, error) { return nil, nil }", want: "a MarshalText method"},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			src := "package dash\n\n" + tc.decl + "\n\ntype RevenueChartProps struct {\n\tTitle string `json:\"title\"`\n\t" + tc.field + "\n}\n"
			dir := writeTree(t, map[string]string{
				"go.mod":               moduleWithGx(t),
				"dash/charts.go":       src,
				"dash/RevenueChart.ts": chartIsland,
			})
			diags := compiler.Check(dir)
			d := diagWith(t, diags, compiler.CodeIslandType)
			if d.Code != "GX6002" {
				t.Fatalf("code = %s, want GX6002", d.Code)
			}
			if !strings.Contains(d.Msg, tc.want) {
				t.Fatalf("GX6002 message = %q, want %q", d.Msg, tc.want)
			}
			wantLine := strings.Count(src[:strings.Index(src, "\t"+tc.field)], "\n") + 1
			if !strings.HasSuffix(d.File, "charts.go") || d.Line != wantLine || d.Col != 2 {
				t.Fatalf("GX6002 position = %s:%d:%d, want charts.go:%d:2", d.File, d.Line, d.Col, wantLine)
			}
			if len(diags) != 1 {
				t.Fatalf("diagnostics = %v, want only GX6002", diags)
			}
		})
	}
}

