// contentBodyFile is the generated body renderer of one package.
const contentBodyFile = "gxcontent_gx.go"

// renderContentBodies generates one typed body renderer per collection
// (REQ-CNT-03). The output maps a file path to its source.
func renderContentBodies(colls []contentCollection) map[string][]byte {
	byPkg := map[string][]contentCollection{}
	var dirs []string
	for _, coll := range colls {
		if coll.pkgDir == "" || coll.varName == "" || coll.bare {
			continue
		}
		if _, ok := byPkg[coll.pkgDir]; !ok {
			dirs = append(dirs, coll.pkgDir)
		}
		byPkg[coll.pkgDir] = append(byPkg[coll.pkgDir], coll)
	}
	sort.Strings(dirs)
	out := map[string][]byte{}
	for _, dir := range dirs {
		src, err := renderContentFile(byPkg[dir])
		if err != nil {
			continue
		}
		out[filepath.Join(dir, contentBodyFile)] = src
	}
	return out
}

// renderContentFile renders every collection body function of one package.
func renderContentFile(colls []contentCollection) ([]byte, error) {
	w := &contentWriter{imports: map[string]string{}}
	for _, coll := range colls {
		w.coll = coll
		if err := w.collection(coll); err != nil {
			return nil, err
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gx. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", colls[0].pkgName)
	b.WriteString("import (\n")
	b.WriteString("\tgx \"github.com/alternayte/gx\"\n")
	b.WriteString("\t\"github.com/alternayte/gx/content\"\n")
	paths := make([]string, 0, len(w.imports))
	for path := range w.imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		alias := w.imports[path]
		if alias == filepath.Base(path) && !strings.ContainsAny(alias, "-.") {
			fmt.Fprintf(&b, "\t%q\n", path)
			continue
		}
		fmt.Fprintf(&b, "\t%s %q\n", alias, path)
	}
	b.WriteString(")\n\n")
	b.Write(w.buf.Bytes())
	b.WriteString("\n// gxContentMarkdown renders one prose chunk of a content body.\nfunc gxContentMarkdown(s string) gx.Node {\n\tnode, err := content.Body([]byte(s))\n\tif err != nil {\n\t\treturn gx.Text(\"\")\n\t}\n\treturn node\n}\n")
	src, err := imports.Process(contentBodyFile, b.Bytes(), nil)
	if err != nil {
		return nil, err
	}
	return src, nil
}

// contentWriter renders the body functions of one package.
type contentWriter struct {
	coll    contentCollection
	buf     bytes.Buffer
	imports map[string]string // path -> alias
}

// collection renders one <Var>Body function.
func (w *contentWriter) collection(coll contentCollection) error {
	fmt.Fprintf(&w.buf, "// %sBody renders the component tags of the %s collection (REQ-CNT-03).\n", coll.varName, coll.varName)
	fmt.Fprintf(&w.buf, "func %sBody(e gx.Entry[%s]) gx.Node {\n	switch e.Slug {\n", coll.varName, coll.metaType)
	if coll.metaPkgPath != "" && coll.metaPkgPath != coll.pkgPath {
		w.imports[coll.metaPkgPath] = coll.metaPkgName
	}
	for _, path := range markdownFiles(coll.dir) {
		src, err := readContent(path, nil)
		if err != nil {
			continue
		}
		slug := contentFileSlug(coll.dir, path)
		body, _ := splitContentBody(src)
		nodes, _ := parseContentTree(string(body), 0)
		expr, err := w.nodes(nodes)
		if err != nil {
			return err
		}
		fmt.Fprintf(&w.buf, "\tcase %q:\n\t\treturn %s\n", slug, expr)
	}
	w.buf.WriteString("\t}\n\treturn gxContentMarkdown(string(e.Body))\n}\n\n")
	return nil
}

// nodes renders a node list as one gx.Node expression.
func (w *contentWriter) nodes(nodes []contentNode) (string, error) {
	var parts []string
	for _, node := range nodes {
		expr, err := w.node(node)
		if err != nil {
			return "", err
		}
		if expr != "" {
			parts = append(parts, expr)
		}
	}
	switch len(parts) {
	case 0:
		return "gx.Text(\"\")", nil
	case 1:
		return parts[0], nil
	default:
		return "gx.Frag(" + strings.Join(parts, ", ") + ")", nil
	}
}

// node renders one node.
func (w *contentWriter) node(node contentNode) (string, error) {
	if node.tag == nil {
		if strings.TrimSpace(node.text) == "" {
			return "", nil
		}
		return "gxContentMarkdown(" + strconv.Quote(node.text) + ")", nil
	}
	comp, ok := w.coll.comps[node.tag.name]
	if !ok {
		// The content check reports the undeclared component.
		return "", nil
	}
	var fields []string
	for _, attr := range node.tag.attrs {
		prop, ok := comp.props[attr.name]
		if !ok {
			continue
		}
		value, err := w.attr(comp, prop, attr)
		if err != nil {
			return "", err
		}
		fields = append(fields, prop.Name+": "+value)
	}
	if len(node.kids) > 0 {
		if prop, ok := comp.props["children"]; ok {
			children, err := w.nodes(node.kids)
			if err != nil {
				return "", err
			}
			fields = append(fields, prop.Name+": "+children)
		}
	}
	props := comp.propsType + "{" + strings.Join(fields, ", ") + "}"
	return w.componentRef(comp) + "(" + props + ")", nil
}

// componentRef returns the component function as written in the generated
// file.
func (w *contentWriter) componentRef(comp contentComp) string {
	if comp.pkgPath == "" || comp.pkgPath == w.coll.pkgPath {
		return comp.name
	}
	w.imports[comp.pkgPath] = comp.pkgName
	return comp.pkgName + "." + comp.name
}

// attr renders one attribute value.
func (w *contentWriter) attr(comp contentComp, prop Prop, attr contentAttr) (string, error) {
	if attr.expr {
		expr := strings.TrimSpace(attr.value)
		expr = strings.ReplaceAll(expr, "meta.", "e.Meta.")
		return expr, nil
	}
	if attr.value == "" {
		return "true", nil
	}
	if prop.Type == "string" {
		return strconv.Quote(attr.value), nil
	}
	if isBuiltinPropType(prop.Type) {
		return "", fmt.Errorf("content: a static value on the %s prop of %s", attr.name, comp.name)
	}
	return prop.Type + "(" + strconv.Quote(attr.value) + ")", nil
}

// isBuiltinPropType reports whether a prop type is a Go builtin.
func isBuiltinPropType(t string) bool {
	switch t {
	case "string", "bool", "error", "any",
		"int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "complex64", "complex128", "byte", "rune":
		return true
	}
	return false
}

// contentFileSlug returns the entry slug of one content file.
func contentFileSlug(dir, path string) string {
	rel, err := filepath.Rel(dir, path)
	if err != nil {
		return ""
	}
	return strings.TrimSuffix(filepath.ToSlash(rel), ".md")
}
