// Package icons pins an icon set and generates one .gx component per icon
// (REQ-STY-06). Packs come from Iconify JSON and are pinned by sha256 in
// gx.lock.
package icons

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

// DefaultBaseURL is the Iconify JSON pack root.
const DefaultBaseURL = "https://raw.githubusercontent.com/iconify/icon-sets/master/json"

// Pack is one Iconify JSON pack.
type Pack struct {
	Prefix  string           `json:"prefix"`
	Width   float64          `json:"width"`
	Height  float64          `json:"height"`
	Icons   map[string]Icon  `json:"icons"`
	Aliases map[string]Alias `json:"aliases"`
}

// Icon is one icon of a pack.
type Icon struct {
	Body string `json:"body"`
}

// Alias points at another icon of the pack.
type Alias struct {
	Parent string `json:"parent"`
}

// Entry is the gx.lock pin of one set.
type Entry struct {
	Version string `json:"version"`
	SHA256  string `json:"sha256"`
}

// Options configure one pin run.
type Options struct {
	// Dir is the module root.
	Dir string
	// Set is the icon set name, for example "lucide".
	Set string
	// Version is the pinned version label.
	Version string
	// Out is the output package directory, relative to Dir. The default is
	// ui/icons/<set>.
	Out string
	// BaseURL overrides the pack root.
	BaseURL string
	// Client is the HTTP client.
	Client *http.Client
}

// Pin fetches the pack, pins its sha256 in gx.lock and writes one .gx file
// per icon (REQ-STY-06).
func Pin(ctx context.Context, opt Options) error {
	if opt.Set == "" || opt.Version == "" {
		return fmt.Errorf("icons: set and version are required")
	}
	base := opt.BaseURL
	if base == "" {
		base = os.Getenv("GX_ICONIFY_BASE")
	}
	if base == "" {
		base = DefaultBaseURL
	}
	url := strings.TrimSuffix(base, "/") + "/" + opt.Set + ".json"
	client := opt.Client
	if client == nil {
		client = &http.Client{Timeout: 5 * time.Minute}
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return err
	}
	resp, err := client.Do(req)
	if err != nil {
		return fmt.Errorf("icons: fetch %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("icons: fetch %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	hexSum := hex.EncodeToString(sum[:])
	if err := checkPin(opt.Dir, opt.Set, hexSum); err != nil {
		return err
	}
	var pack Pack
	if err := json.Unmarshal(data, &pack); err != nil {
		return fmt.Errorf("icons: parse %s: %w", url, err)
	}
	if len(pack.Icons) == 0 {
		return fmt.Errorf("icons: pack %s holds no icons", opt.Set)
	}
	outDir := opt.Out
	if outDir == "" {
		outDir = filepath.Join("ui", "icons", opt.Set)
	}
	if !filepath.IsAbs(outDir) {
		outDir = filepath.Join(opt.Dir, outDir)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	for _, name := range sortedNames(pack) {
		body, ok := pack.body(name)
		if !ok || !validBody(body) {
			continue
		}
		src := renderIcon(opt.Set, name, body)
		path := filepath.Join(outDir, goName(name)+".gx")
		if old, err := os.ReadFile(path); err == nil && string(old) == src {
			continue
		}
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			return err
		}
	}
	return saveLock(opt.Dir, opt.Set, Entry{Version: opt.Version, SHA256: hexSum})
}

// body returns the inner markup of an icon, resolving aliases.
func (p Pack) body(name string) (string, bool) {
	if icon, ok := p.Icons[name]; ok {
		return icon.Body, true
	}
	alias, ok := p.Aliases[name]
	if !ok {
		return "", false
	}
	return p.body(alias.Parent)
}

func sortedNames(p Pack) []string {
	seen := map[string]bool{}
	var names []string
	for name := range p.Icons {
		if !seen[name] {
			seen[name] = true
			names = append(names, name)
		}
	}
	for name := range p.Aliases {
		if !seen[name] {
			seen[name] = true
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

// validBody accepts only markup that cannot break out of the svg.
func validBody(body string) bool {
	if body == "" || strings.Contains(body, "&#") {
		return false
	}
	lower := strings.ToLower(body)
	if strings.Contains(lower, "<script") || strings.Contains(lower, "javascript:") ||
		strings.Contains(lower, "onload") || strings.Contains(lower, "onerror") {
		return false
	}
	return strings.Contains(body, "<")
}

// renderIcon renders one .gx component.
func renderIcon(set, name, body string) string {
	var b strings.Builder
	b.WriteString("// Code generated by gx icons. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName(set))
	b.WriteString("import \"github.com/alternayte/gx\"\n\n")
	b.WriteString("props {\n")
	b.WriteString("  Label string\n")
	b.WriteString("  Class string\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "{gx.Icon(%s, gx.IconProps{Label: p.Label, Class: p.Class})}\n", strconv.Quote(body))
	return b.String()
}

// packageName makes a Go package name from a set name.
func packageName(set string) string {
	name := strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			return r
		case r >= 'A' && r <= 'Z':
			return r + ('a' - 'A')
		default:
			return -1
		}
	}, set)
	if name == "" || (name[0] >= '0' && name[0] <= '9') {
		return "icons"
	}
	return name
}

// goName makes an exported Go identifier from an icon name.
func goName(name string) string {
	var b strings.Builder
	upper := true
	for _, r := range name {
		switch {
		case r == '-' || r == '_' || r == ' ' || r == '.':
			upper = true
		case r >= 'a' && r <= 'z':
			if upper {
				b.WriteRune(r - ('a' - 'A'))
				upper = false
			} else {
				b.WriteRune(r)
			}
		case r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
			upper = false
		}
	}
	out := b.String()
	if out == "" || (out[0] >= '0' && out[0] <= '9') {
		return "Icon" + out
	}
	return out
}

// checkPin fails when gx.lock already pins the set with another hash.
func checkPin(dir, set, sum string) error {
	entries, err := readLock(dir)
	if err != nil {
		return err
	}
	if entry, ok := entries[set]; ok && entry.SHA256 != "" && entry.SHA256 != sum {
		return fmt.Errorf("icons: %s sha256 = %s, gx.lock pins %s", set, sum, entry.SHA256)
	}
	return nil
}

// readLock reads the icons section of gx.lock.
func readLock(dir string) (map[string]Entry, error) {
	path := filepath.Join(dir, "gx.lock")
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return map[string]Entry{}, nil
		}
		return nil, err
	}
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("icons: gx.lock: %w", err)
	}
	entries := map[string]Entry{}
	if section, ok := raw["icons"]; ok {
		if err := json.Unmarshal(section, &entries); err != nil {
			return nil, fmt.Errorf("icons: gx.lock icons: %w", err)
		}
	}
	return entries, nil
}

// saveLock merges one pin into gx.lock without touching other sections.
func saveLock(dir, set string, entry Entry) error {
	path := filepath.Join(dir, "gx.lock")
	raw := map[string]json.RawMessage{}
	if data, err := os.ReadFile(path); err == nil {
		if err := json.Unmarshal(data, &raw); err != nil {
			return fmt.Errorf("icons: gx.lock: %w", err)
		}
	}
	entries, err := readLock(dir)
	if err != nil {
		return err
	}
	entries[set] = entry
	section, err := json.Marshal(entries)
	if err != nil {
		return err
	}
	raw["icons"] = section
	data, err := json.MarshalIndent(raw, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return os.WriteFile(path, data, 0o644)
}
