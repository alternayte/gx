// Writes the Go table of gx.Cx from the tailwind-merge default config. It
// serializes the class map that tailwind-merge itself builds, so the table
// holds no hand-copied class group.
import { resolve, join } from 'node:path'
import { writeFileSync, readFileSync } from 'node:fs'

const [srcArg, outFile] = process.argv.slice(2)
const src = resolve(srcArg)
const { getDefaultConfig } = await import(join(src, 'lib/default-config.ts'))
const { createClassMap } = await import(join(src, 'lib/class-group-utils.ts'))
const V = await import(join(src, 'lib/validators.ts'))
const version = JSON.parse(readFileSync(join(src, '../package.json'), 'utf8')).version

const cfg = getDefaultConfig()
const validatorName = new Map<Function, string>()
for (const [name, fn] of Object.entries(V)) if (typeof fn === 'function') validatorName.set(fn as Function, name)

// Class group ids, in config order. Id 0 means "no group".
const groupIDs = new Map<string, number>()
const groupNames: string[] = ['']
const groupID = (name: string) => {
  let id = groupIDs.get(name)
  if (id === undefined) {
    id = groupNames.length
    groupIDs.set(name, id)
    groupNames.push(name)
  }
  return id
}
for (const name of Object.keys(cfg.classGroups)) groupID(name)

const validators: string[] = []
const validatorID = (fn: Function) => {
  const name = validatorName.get(fn)
  if (!name) throw new Error('a class group uses a validator that validators.ts does not export: ' + fn.toString().slice(0, 60))
  let id = validators.indexOf(name)
  if (id < 0) {
    id = validators.length
    validators.push(name)
  }
  return id
}

type Node = { nextPart: Map<string, Node>; validators: { classGroupId: string; validator: Function }[] | null; classGroupId?: string }
const nodes: { group: number; kidStart: number; kidEnd: number; valStart: number; valEnd: number }[] = []
const kids: { part: string; node: number }[] = []
const vals: { validator: number; group: number }[] = []
// Breadth-first, so the children of one node are one run of the kid table.
const queue: Node[] = [createClassMap(cfg)]
const index = new Map<Node, number>([[queue[0]!, 0]])
for (let i = 0; i < queue.length; i++) {
  const n = queue[i]!
  const parts = [...n.nextPart.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
  const kidStart = kids.length
  for (const part of parts) {
    const child = n.nextPart.get(part)!
    index.set(child, queue.length)
    kids.push({ part, node: queue.length })
    queue.push(child)
  }
  const valStart = vals.length
  for (const v of n.validators ?? []) vals.push({ validator: validatorID(v.validator), group: groupID(v.classGroupId) })
  nodes.push({ group: n.classGroupId ? groupID(n.classGroupId) : 0, kidStart, kidEnd: kids.length, valStart, valEnd: vals.length })
}

const q = (s: string) => JSON.stringify(s)
const ids = (names: readonly string[]) => names.map((n) => groupID(n)).join(', ')
const goName = (v: string) => 'tw' + v[0]!.toUpperCase() + v.slice(1)

let out = `// Code generated by tools/twmerge from tailwind-merge ${version}. DO NOT EDIT.

package gx

// twMergeVersion is the tailwind-merge release this table comes from.
const twMergeVersion = ${q(version)}

// Validator ids, in the order the class map first uses them.
const (
`
validators.forEach((v, i) => {
  out += `\t${goName(v)}${i === 0 ? ' = iota' : ''}\n`
})
out += `)

// twGroupNames holds the class group ids of tailwind-merge. Index 0 is "no
// group".
var twGroupNames = [...]string{
${groupNames.map((n) => `\t${q(n)},`).join('\n')}
}

// twNodes is the class map: node 0 is the root.
var twNodes = [...]twNode{
${nodes.map((n) => `\t{${n.group}, ${n.kidStart}, ${n.kidEnd}, ${n.valStart}, ${n.valEnd}},`).join('\n')}
}

// twKids holds the children of every node, sorted by part inside one node.
var twKids = [...]twKid{
${kids.map((k) => `\t{${q(k.part)}, ${k.node}},`).join('\n')}
}

// twVals holds the validators of every node, in the order tailwind-merge
// tries them.
var twVals = [...]twVal{
${vals.map((v) => `\t{${goName(validators[v.validator]!)}, ${v.group}},`).join('\n')}
}

// twConflicts holds, for each class group id, the groups it removes.
var twConflicts = [...][]uint16{
${Object.entries(cfg.conflictingClassGroups as Record<string, string[]>).map(([g, c]) => `\t${groupID(g)}: {${ids(c)}}, // ${g}`).join('\n')}
\t${groupNames.length - 1 + 0}: nil,
}

// twModifierConflicts holds, for each class group id, the groups it removes
// only when the class has a postfix modifier, as in text-lg/7.
var twModifierConflicts = [...][]uint16{
${Object.entries(cfg.conflictingClassGroupModifiers as Record<string, string[]>).map(([g, c]) => `\t${groupID(g)}: {${ids(c)}}, // ${g}`).join('\n')}
\t${groupNames.length - 1 + 0}: nil,
}

// twPostfixLookup marks the groups whose classes can hold a "/" that is
// not a postfix modifier.
var twPostfixLookup = [...]bool{
${(cfg.postfixLookupClassGroups as string[]).map((g) => `\t${groupID(g)}: true, // ${g}`).join('\n')}
\t${groupNames.length - 1 + 0}: false,
}

// twOrderSensitive holds the modifiers whose position changes the meaning
// of a class.
var twOrderSensitive = map[string]bool{
${(cfg.orderSensitiveModifiers as string[]).map((m) => `\t${q(m)}: true,`).join('\n')}
}
`
writeFileSync(resolve(outFile), out)
console.log(`tailwind-merge ${version}: ${groupNames.length - 1} groups, ${nodes.length} nodes, ${kids.length} parts, ${vals.length} validators`)
